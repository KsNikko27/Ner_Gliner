"""PostgreSQL storage for NERFactory, using psycopg2.

Numeric person IDs (BIGINT IDENTITY) replace UUID person IDs.
Article metadata and an optional HTML snapshot are stored in article_archive.
"""
from __future__ import annotations

import os
from pathlib import Path
from typing import Any

import psycopg2


ATTRIBUTE_FIELDS = {
    "job_titles": "Job Title",
    "organizations": "Organization",
    "locations": "Location",
    "other_entities": "Other",
}


def _norm(value: str) -> str:
    return " ".join(str(value).casefold().split())


def _attribute_parts(attribute: Any) -> tuple[str, float]:
    if isinstance(attribute, dict):
        value = str(attribute.get("value", "")).strip()
        try:
            confidence = float(attribute.get("confidence", 0) or 0)
        except (TypeError, ValueError):
            confidence = 0.0
    else:
        value, confidence = str(attribute).strip(), 0.0
    return value, confidence


class PostgresStorage:
    """PostgreSQL storage using psycopg2.

    Configure with DATABASE_URL or PGHOST, PGPORT, PGDATABASE, PGUSER,
    PGPASSWORD environment variables.
    """

    def __init__(self, dsn: str | None = None):
        self.dsn = dsn or os.getenv("DATABASE_URL")
        self.conninfo = None
        if not self.dsn:
            self.conninfo = {
                "host": os.getenv("PGHOST", "localhost"),
                "port": int(os.getenv("PGPORT", "5432")),
                "dbname": os.getenv("PGDATABASE", "ner_db"),
                "user": os.getenv("PGUSER", "postgres"),
                "password": os.getenv("PGPASSWORD", "0000"),
            }

    def _connect(self):
        if self.dsn:
            return psycopg2.connect(self.dsn)
        return psycopg2.connect(**self.conninfo)

    def initialize(self) -> None:
        """Create tables and migrate a previous schema when possible.

        WARNING: backs up the database before running this migration.
        If the old `people.person_id` is UUID, people and dependent tables are
        rebuilt with numeric person IDs. Existing person records are preserved,
        but old UUID-based person IDs are replaced with new integer IDs.
        """
        conn = self._connect()
        try:
            with conn:
                with conn.cursor() as cur:
                    # Check whether people already exists and its ID type.
                    cur.execute("""
                        SELECT data_type
                        FROM information_schema.columns
                        WHERE table_schema = 'public'
                          AND table_name = 'people'
                          AND column_name = 'person_id'
                    """)
                    person_id_info = cur.fetchone()
                    old_people_table = person_id_info is not None
                    old_person_id_type = person_id_info[0] if person_id_info else None

                    # Ensure article archive exists.
                    cur.execute("""
                        CREATE TABLE IF NOT EXISTS article_archive (
                            article_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            source_url TEXT NOT NULL UNIQUE,
                            page_title TEXT,
                            html_snapshot TEXT,
                            saved_at TIMESTAMPTZ NOT NULL DEFAULT now()
                        )
                    """)

                    # Migrate legacy articles into archive before removing the table.
                    cur.execute("SELECT to_regclass('public.articles')")
                    legacy_articles = cur.fetchone()[0] is not None
                    if legacy_articles:
                        cur.execute("""
                            INSERT INTO article_archive(article_id, source_url)
                            OVERRIDING SYSTEM VALUE
                            SELECT article_id, source
                            FROM articles
                            ON CONFLICT (article_id) DO NOTHING
                        """)
                        cur.execute("""
                            SELECT setval(
                                pg_get_serial_sequence('article_archive', 'article_id'),
                                GREATEST(COALESCE((SELECT MAX(article_id) FROM article_archive), 1), 1),
                                EXISTS (SELECT 1 FROM article_archive)
                            )
                        """)

                    if old_people_table and old_person_id_type != "bigint":
                        # Drop dependents first so UUID -> BIGINT can be changed cleanly.
                        cur.execute("DROP TABLE IF EXISTS attribute_mentions CASCADE")
                        cur.execute("DROP TABLE IF EXISTS person_mentions CASCADE")
                        cur.execute("DROP TABLE IF EXISTS person_attributes CASCADE")

                        # Preserve people rows while assigning fresh numeric IDs.
                        cur.execute("""
                            ALTER TABLE people RENAME TO people_old_uuid
                        """)
                        cur.execute("""
                            CREATE TABLE people (
                                person_id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
                                full_name TEXT NOT NULL,
                                first_name TEXT,
                                last_name TEXT,
                                patronymic TEXT,
                                created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
                                updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
                            )
                        """)
                        cur.execute("""
                            INSERT INTO people(full_name, first_name, last_name, patronymic, created_at, updated_at)
                            SELECT full_name, first_name, last_name, patronymic, created_at, updated_at
                            FROM people_old_uuid
                            ORDER BY created_at, full_name
                        """)
                        cur.execute("DROP TABLE people_old_uuid")
                    else:
                        cur.execute("""
                            CREATE TABLE IF NOT EXISTS people (
                                person_id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
                                full_name TEXT NOT NULL,
                                first_name TEXT,
                                last_name TEXT,
                                patronymic TEXT,
                                created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
                                updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
                            )
                        """)

                    cur.execute("""
                        CREATE TABLE IF NOT EXISTS person_attributes (
                            attribute_id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
                            person_id BIGINT NOT NULL REFERENCES people(person_id) ON DELETE CASCADE,
                            attribute_type TEXT NOT NULL,
                            value TEXT NOT NULL,
                            normalized_value TEXT NOT NULL,
                            confidence DOUBLE PRECISION NOT NULL DEFAULT 0,
                            UNIQUE (person_id, attribute_type, normalized_value)
                        )
                    """)
                    cur.execute("""
                        CREATE TABLE IF NOT EXISTS person_mentions (
                            article_id BIGINT NOT NULL REFERENCES article_archive(article_id) ON DELETE CASCADE,
                            person_id BIGINT NOT NULL REFERENCES people(person_id) ON DELETE CASCADE,
                            mentioned_name TEXT NOT NULL,
                            PRIMARY KEY (article_id, person_id, mentioned_name)
                        )
                    """)
                    cur.execute("""
                        CREATE TABLE IF NOT EXISTS attribute_mentions (
                            article_id BIGINT NOT NULL REFERENCES article_archive(article_id) ON DELETE CASCADE,
                            attribute_id BIGINT NOT NULL REFERENCES person_attributes(attribute_id) ON DELETE CASCADE,
                            PRIMARY KEY (article_id, attribute_id)
                        )
                    """)

                    if legacy_articles:
                        # Drop old table only after archive rows and new schema exist.
                        cur.execute("DROP TABLE articles")

                    cur.execute("""
                        CREATE INDEX IF NOT EXISTS idx_person_attributes_type
                        ON person_attributes(attribute_type)
                    """)
                    cur.execute("""
                        CREATE INDEX IF NOT EXISTS idx_person_attributes_value
                        ON person_attributes(normalized_value)
                    """)
                    cur.execute("""
                        CREATE INDEX IF NOT EXISTS idx_person_mentions_person
                        ON person_mentions(person_id)
                    """)
                    cur.execute("""
                        CREATE INDEX IF NOT EXISTS idx_article_archive_source_url
                        ON article_archive(source_url)
                    """)
        finally:
            conn.close()

    def save_grouped_result(
        self,
        grouped_result: dict[str, Any],
        source_file: str | Path | None = None,
        *,
        source_url: str | None = None,
        html_snapshot: str | None = None,
        page_title: str | None = None,
    ) -> None:
        """Save one article and its NER results.

        Numeric IDs are generated by PostgreSQL. `person_id` values from
        grouped_result are intentionally ignored. To reuse a person across
        multiple articles, provide `person_id` as an integer if it already
        exists in the DB, or supply `person_db_id` in the person dictionary.
        Otherwise, this method matches existing people by full_name (case-insensitive)
        and reuses that numeric ID; if no match exists, PostgreSQL creates one.
        """
        people = grouped_result.get("people", [])
        if not isinstance(people, list):
            raise TypeError("grouped_result['people'] должен быть списком")

        article_url = (source_url or (str(source_file) if source_file is not None else "")).strip()
        if not article_url:
            raise ValueError("Нужно передать source_url (ссылку на статью).")

        conn = self._connect()
        try:
            with conn:
                with conn.cursor() as cur:
                    cur.execute(
                        """
                        INSERT INTO article_archive(source_url, page_title, html_snapshot, saved_at)
                        VALUES (%s, %s, %s, now())
                        ON CONFLICT (source_url) DO UPDATE SET
                            page_title = COALESCE(EXCLUDED.page_title, article_archive.page_title),
                            html_snapshot = COALESCE(EXCLUDED.html_snapshot, article_archive.html_snapshot),
                            saved_at = CASE
                                WHEN EXCLUDED.html_snapshot IS NOT NULL THEN now()
                                ELSE article_archive.saved_at
                            END
                        RETURNING article_id
                        """,
                        (article_url, page_title, html_snapshot),
                    )
                    article_id = cur.fetchone()[0]

                    for person in people:
                        if not isinstance(person, dict):
                            continue
                        full_name = str(person.get("full_name") or "Unknown").strip()
                        requested_db_id = person.get("person_db_id")
                        # Optional numeric DB ID can be supplied explicitly.
                        if requested_db_id is None and isinstance(person.get("person_id"), int):
                            requested_db_id = person["person_id"]

                        if requested_db_id is not None:
                            cur.execute("SELECT person_id FROM people WHERE person_id = %s", (requested_db_id,))
                            row = cur.fetchone()
                            if row is None:
                                raise ValueError(f"person_db_id={requested_db_id} не найден в таблице people")
                            person_id = row[0]
                            cur.execute(
                                """
                                UPDATE people SET
                                    full_name = CASE
                                        WHEN full_name = '' OR full_name = 'Unknown' THEN %s
                                        ELSE full_name END,
                                    first_name = COALESCE(first_name, %s),
                                    last_name = COALESCE(last_name, %s),
                                    patronymic = COALESCE(patronymic, %s),
                                    updated_at = now()
                                WHERE person_id = %s
                                """,
                                (full_name, person.get("first_name"), person.get("last_name"),
                                 person.get("patronymic"), person_id),
                            )
                        else:
                            # Best-effort matching across articles by full name.
                            cur.execute(
                                """
                                SELECT person_id FROM people
                                WHERE lower(full_name) = lower(%s)
                                ORDER BY person_id LIMIT 1
                                """,
                                (full_name,),
                            )
                            row = cur.fetchone()
                            if row:
                                person_id = row[0]
                                cur.execute(
                                    """
                                    UPDATE people SET
                                        first_name = COALESCE(first_name, %s),
                                        last_name = COALESCE(last_name, %s),
                                        patronymic = COALESCE(patronymic, %s),
                                        updated_at = now()
                                    WHERE person_id = %s
                                    """,
                                    (person.get("first_name"), person.get("last_name"),
                                     person.get("patronymic"), person_id),
                                )
                            else:
                                cur.execute(
                                    """
                                    INSERT INTO people(full_name, first_name, last_name, patronymic)
                                    VALUES (%s, %s, %s, %s)
                                    RETURNING person_id
                                    """,
                                    (full_name, person.get("first_name"), person.get("last_name"),
                                     person.get("patronymic")),
                                )
                                person_id = cur.fetchone()[0]

                        cur.execute(
                            """
                            INSERT INTO person_mentions(article_id, person_id, mentioned_name)
                            VALUES (%s, %s, %s) ON CONFLICT DO NOTHING
                            """,
                            (article_id, person_id, full_name),
                        )

                        for field, attribute_type in ATTRIBUTE_FIELDS.items():
                            attributes = person.get(field, []) or []
                            if not isinstance(attributes, (list, tuple, set)):
                                attributes = [attributes]
                            for attribute in attributes:
                                value, confidence = _attribute_parts(attribute)
                                if not value:
                                    continue
                                normalized = _norm(value)
                                cur.execute(
                                    """
                                    INSERT INTO person_attributes
                                        (person_id, attribute_type, value, normalized_value, confidence)
                                    VALUES (%s, %s, %s, %s, %s)
                                    ON CONFLICT (person_id, attribute_type, normalized_value)
                                    DO UPDATE SET confidence = GREATEST(
                                        person_attributes.confidence, EXCLUDED.confidence
                                    )
                                    RETURNING attribute_id
                                    """,
                                    (person_id, attribute_type, value, normalized, confidence),
                                )
                                attribute_id = cur.fetchone()[0]
                                cur.execute(
                                    """
                                    INSERT INTO attribute_mentions(article_id, attribute_id)
                                    VALUES (%s, %s) ON CONFLICT DO NOTHING
                                    """,
                                    (article_id, attribute_id),
                                )
        finally:
            conn.close()

    def get_article_snapshot(self, source_url: str) -> dict[str, Any] | None:
        conn = self._connect()
        try:
            with conn.cursor() as cur:
                cur.execute(
                    """
                    SELECT article_id, source_url, page_title, html_snapshot, saved_at
                    FROM article_archive WHERE source_url = %s
                    """,
                    (source_url,),
                )
                row = cur.fetchone()
                if row is None:
                    return None
                return {
                    "article_id": row[0],
                    "source_url": row[1],
                    "page_title": row[2],
                    "html_snapshot": row[3],
                    "saved_at": row[4],
                }
        finally:
            conn.close()

    def test_connection(self) -> bool:
        conn = self._connect()
        try:
            with conn.cursor() as cur:
                cur.execute("SELECT 1")
                return cur.fetchone()[0] == 1
        finally:
            conn.close()
